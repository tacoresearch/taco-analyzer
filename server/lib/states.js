const BY_CODE = new Map(STATES.map((s) => [s.code, s]));

/** @param {unknown} code */
export function isValidStateCode(code) {
  return typeof code === 'string' && BY_CODE.has(code.toUpperCase());
}

/**
 * Full name for a stored code, falling back to the code itself so unknown
 * historical data still renders.
 * @param {?string} code
 * @returns {string}
 */
export function stateName(code) {
  if (typeof code !== 'string') return '';
  return BY_CODE.get(code.toUpperCase())?.name ?? code;
}
